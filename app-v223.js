const TERM_LABELS=["🌸 1学期ごろ","🍁 2学期ごろ","❄️ 3学期ごろ"];
function splitTerms(arr){
 let n=arr.length,a=Math.ceil(n/3),b=Math.ceil((n-a)/2);
 return [arr.slice(0,a),arr.slice(a,a+b),arr.slice(a+b)];
}
function textbookMap(){
 head("📚 河口湖・教科書順の単元",child);
 A.append(e("div","card",`<h2>学校の学習順から探す</h2><p>学年 → 学期ごろ → 単元の順に選べます。</p><p class="tiny">学校の授業進度は前後するため「学期ごろ」と表示します。ここは教科書順へ移行するための単元マップです。</p>`));
 ["国語","算数","理科","社会","外国語"].forEach(sub=>{
   let d=e("details","card");let sm=document.createElement("summary");sm.innerHTML=`<b>${sub}</b> <span class="tiny">${TEXTBOOK_INFO[sub]}</span>`;d.append(sm);
   for(let g=1;g<=6;g++){
     let arr=TEXTBOOK_MAP[sub][g];if(!arr)continue;
     let gd=e("details","soft");let gs=document.createElement("summary");gs.innerHTML=`小学${g}年`;gd.append(gs);
     splitTerms(arr).forEach((part,ti)=>{
       if(!part.length)return;
       gd.append(e("h3","term-title",TERM_LABELS[ti]));
       part.forEach(name=>{
         let c=e("div","unit-pick",`<b>${name}</b><br><span class="tiny">${TERM_LABELS[ti]}｜教科書順ナビ</span>`);
         c.onclick=()=>{
           if(sub==="国語"){japaneseGrade=g;localStorage.setItem("ponoJapaneseGrade",g);japaneseStart()}
           else if(sub==="算数")mathUnitSelect(g);
           else start(sub==="外国語"?"外国語活動":sub);
         };
         gd.append(c);
       });
     });d.append(gd);
   } A.append(d);
 });
 A.append(e("div","card soft",`<b>現在の教材との接続について</b><p class="tiny">既にPono教材がある単元は従来画面へつなぎます。まだ教材がない単元は、今後「この単元で学ぶこと → ①まなぶ → ②一緒に → ③自分で → まとめ → ふりかえり → あとから確認」を追加します。</p>`));
}
